"""SQLAlchemy Core table definitions for Alembic and query building."""

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    ARRAY,
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    MetaData,
    String,
    Table,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

metadata = MetaData()

users = Table(
    "users",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("handle", Text, unique=True, nullable=False),
    Column("email", Text, unique=True, nullable=False),
    Column("api_key", Text, unique=True, nullable=False),
    Column("role", String(20), nullable=False, server_default="contributor"),
    Column("signing_public_key", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
)

categories = Table(
    "categories",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("slug", Text, unique=True, nullable=False),
    Column("name", Text, nullable=False),
    Column("description", Text, nullable=True),
    Column("parent_id", UUID, ForeignKey("categories.id"), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
)

skills = Table(
    "skills",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("slug", Text, unique=True, nullable=False),
    Column("name", Text, nullable=False),
    Column("description", Text, nullable=False),
    Column("content", Text, nullable=False),
    Column("category_id", UUID, ForeignKey("categories.id"), nullable=False),
    Column("tags", ARRAY(Text), nullable=False, server_default="{}"),
    Column("scope", String(20), nullable=False, server_default="community"),
    Column("version", Text, nullable=False),
    Column("author_id", UUID, ForeignKey("users.id"), nullable=False),
    Column("signature", Text, nullable=True),
    Column("trust_tier", String(20), nullable=False, server_default="experimental"),
    Column("cost_profile", String(20), nullable=False, server_default="free"),
    Column("cost_drivers", ARRAY(Text), nullable=False, server_default="{}"),
    Column("estimated_duration", String(20), nullable=False, server_default="fast"),
    Column("dependencies", JSONB, nullable=False, server_default="{}"),
    Column("eval_spec", JSONB, nullable=False, server_default="{}"),
    Column("extends", Text, nullable=True),
    Column("embedding", Vector(1536), nullable=True),
    # M2: evaluation and signing columns
    Column(
        "latest_eval_job_id",
        UUID,
        ForeignKey("eval_jobs.id", use_alter=True, name="fk_skills_latest_eval_job"),
        nullable=True,
    ),
    Column("composite_score", Float, nullable=True),
    Column("eval_status", String(20), nullable=True, server_default="pending"),
    Column("signature_key_fingerprint", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Index("idx_skills_category", "category_id"),
    Index("idx_skills_trust_tier", "trust_tier"),
    Index("idx_skills_scope", "scope"),
    Index("idx_skills_tags", "tags", postgresql_using="gin"),
)

skill_versions = Table(
    "skill_versions",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("skill_id", UUID, ForeignKey("skills.id", ondelete="CASCADE"), nullable=False),
    Column("version", Text, nullable=False),
    Column("content", Text, nullable=False),
    Column("dependencies", JSONB, nullable=False, server_default="{}"),
    Column("eval_spec", JSONB, nullable=False, server_default="{}"),
    Column("cost_profile", String(20), nullable=False, server_default="free"),
    Column("cost_drivers", ARRAY(Text), nullable=False, server_default="{}"),
    Column("estimated_duration", String(20), nullable=False, server_default="fast"),
    Column("extends", Text, nullable=True),
    Column("signature", Text, nullable=True),
    Column("author_id", UUID, ForeignKey("users.id"), nullable=False),
    Column("changelog", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    UniqueConstraint("skill_id", "version", name="uq_skill_versions_skill_version"),
    Index("idx_skill_versions_skill", "skill_id"),
)

# --- M2: Evaluation pipeline tables ---

eval_jobs = Table(
    "eval_jobs",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("skill_id", UUID, ForeignKey("skills.id"), nullable=False),
    Column("skill_version", Text, nullable=False),
    Column("content_hash", Text, nullable=False),
    Column("trigger_type", Text, nullable=False),
    Column("status", Text, nullable=False, server_default="pending"),
    Column("structural_report", JSONB, nullable=True),
    Column("composite_score", Float, nullable=True),
    Column("dimension_scores", JSONB, nullable=True),
    Column("dimension_confidence", JSONB, nullable=True),
    Column("injection_flagged", Boolean, nullable=False, server_default="false"),
    Column("sandbox_passed", Boolean, nullable=True),
    Column("overall_confidence", Float, nullable=True),
    Column("evaluator_version", Text, nullable=False),
    Column("started_at", DateTime(timezone=True), nullable=True),
    Column("completed_at", DateTime(timezone=True), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Index("idx_eval_jobs_skill", "skill_id"),
    Index("idx_eval_jobs_status", "status"),
    Index("idx_eval_jobs_trigger", "trigger_type"),
)

eval_dimension_runs = Table(
    "eval_dimension_runs",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column(
        "eval_job_id",
        UUID,
        ForeignKey("eval_jobs.id", ondelete="CASCADE"),
        nullable=False,
    ),
    Column("dimension", Text, nullable=False),
    Column("run_index", Integer, nullable=False),
    Column("score", Float, nullable=False),
    Column("evidence", JSONB, nullable=False),
    Column("injection_detected", Boolean, nullable=False, server_default="false"),
    Column("injection_detail", Text, nullable=True),
    Column("confidence", Float, nullable=False),
    Column("prompt_variant", Text, nullable=False),
    Column("model_id", Text, nullable=False),
    Column("latency_ms", Integer, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    UniqueConstraint("eval_job_id", "dimension", "run_index", name="uq_eval_runs_job_dim_idx"),
    Index("idx_eval_runs_job", "eval_job_id"),
)

trust_audit_log = Table(
    "trust_audit_log",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("skill_id", UUID, ForeignKey("skills.id"), nullable=False),
    Column("previous_tier", Text, nullable=False),
    Column("new_tier", Text, nullable=False),
    Column("reason", Text, nullable=False),
    Column("eval_job_id", UUID, ForeignKey("eval_jobs.id"), nullable=True),
    Column("promoted_by", UUID, ForeignKey("users.id"), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Index("idx_trust_audit_skill", "skill_id"),
)

# --- M3: Capability composition tables ---

capabilities = Table(
    "capabilities",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("slug", Text, unique=True, nullable=False),
    Column("name", Text, nullable=False),
    Column("description", Text, nullable=False),
    Column("category_id", UUID, ForeignKey("categories.id"), nullable=False),
    Column("tags", ARRAY(Text), nullable=False, server_default="{}"),
    Column("scope", String(20), nullable=False, server_default="community"),
    Column("version", Text, nullable=False),
    Column("author_id", UUID, ForeignKey("users.id"), nullable=False),
    Column("trust_tier", String(20), nullable=False, server_default="experimental"),
    Column("steps", JSONB, nullable=False),
    Column("preconditions", JSONB, nullable=False, server_default="[]"),
    Column("expected_outcome", Text, nullable=True),
    Column("data_flow", JSONB, nullable=False, server_default="[]"),
    Column("dependencies", JSONB, nullable=False, server_default="{}"),
    Column("cost_profile", String(20), nullable=False, server_default="free"),
    Column("cost_drivers", ARRAY(Text), nullable=False, server_default="{}"),
    Column("estimated_duration", String(20), nullable=False, server_default="slow"),
    Column("eval_spec", JSONB, nullable=False, server_default="{}"),
    Column("extends", Text, nullable=True),
    Column("embedding", Vector(1536), nullable=True),
    Column("eval_status", String(20), nullable=True),
    Column("composite_score", Float, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Column("updated_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Index("idx_capabilities_category", "category_id"),
    Index("idx_capabilities_trust_tier", "trust_tier"),
    Index("idx_capabilities_scope", "scope"),
    Index("idx_capabilities_tags", "tags", postgresql_using="gin"),
)

capability_versions = Table(
    "capability_versions",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column(
        "capability_id",
        UUID,
        ForeignKey("capabilities.id", ondelete="CASCADE"),
        nullable=False,
    ),
    Column("version", Text, nullable=False),
    Column("steps", JSONB, nullable=False),
    Column("preconditions", JSONB, nullable=True),
    Column("expected_outcome", Text, nullable=True),
    Column("data_flow", JSONB, nullable=True),
    Column("dependencies", JSONB, nullable=True),
    Column("cost_profile", String(20), nullable=True),
    Column("cost_drivers", ARRAY(Text), nullable=True),
    Column("estimated_duration", String(20), nullable=True),
    Column("eval_spec", JSONB, nullable=True),
    Column("extends", Text, nullable=True),
    Column("author_id", UUID, ForeignKey("users.id"), nullable=False),
    Column("changelog", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    UniqueConstraint("capability_id", "version", name="uq_capability_versions_cap_version"),
    Index("idx_capability_versions_capability", "capability_id"),
)

signing_keys = Table(
    "signing_keys",
    metadata,
    Column("id", UUID, primary_key=True, server_default=text("gen_random_uuid()")),
    Column("user_id", UUID, ForeignKey("users.id"), nullable=False),
    Column("public_key", LargeBinary, nullable=False),
    Column("fingerprint", Text, nullable=False, unique=True),
    Column("label", Text, nullable=True),
    Column("revoked_at", DateTime(timezone=True), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False, server_default=text("now()")),
    Index("idx_signing_keys_user", "user_id"),
    Index("idx_signing_keys_fingerprint", "fingerprint"),
)
